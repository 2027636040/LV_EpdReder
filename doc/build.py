"""Bundle repository Markdown for the offline documentation viewer."""

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent


def collect(root):
    catalog = json.loads((root / "doc/catalog.json").read_text(encoding="utf-8"))
    documents = []
    seen = set()
    groups = []
    for group in catalog["groups"]:
        ids = []
        for name, title in group["documents"]:
            path = PurePosixPath(name)
            if path.is_absolute() or ".." in path.parts or "\\" in name or path.suffix != ".md":
                raise ValueError(f"Invalid Markdown path: {name}")
            if name in seen:
                raise ValueError(f"Duplicate document: {name}")
            source = (root / name).resolve()
            if not source.is_relative_to(root.resolve()):
                raise ValueError(f"Document outside repository: {name}")
            markdown = source.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
            seen.add(name)
            ids.append(name)
            documents.append({
                "id": name, "title": title, "group": group["title"],
                "markdown": markdown,
                "sha256": hashlib.sha256(markdown.encode("utf-8")).hexdigest(),
            })
        groups.append({"title": group["title"], "description": group["description"], "ids": ids})
    missing = sorted(p.relative_to(root).as_posix() for p in (root / "docs").rglob("*.md")
                     if p.relative_to(root).as_posix() not in seen)
    if missing:
        raise ValueError("Add documents to doc/catalog.json: " + ", ".join(missing))
    return {"version": 1, "title": catalog["title"], "groups": groups, "documents": documents}


def serialize(data):
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    payload = payload.replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return "// Generated by doc/build.py; edit the source Markdown instead.\nwindow.EPD_DOCS=" + payload + ";\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that the tracked bundle is up to date")
    args = parser.parse_args()
    try:
        data = collect(ROOT)
        result = serialize(data)
        output = ROOT / "doc/assets/content.js"
        if args.check:
            if not output.is_file() or output.read_text(encoding="utf-8") != result:
                parser.exit(1, "Documentation bundle is stale. Run: python doc/build.py\n")
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(result, encoding="utf-8", newline="\n")
        print(f"{'Checked' if args.check else 'Built'} {len(data['documents'])} documents: {output}")
    except (ValueError, OSError, KeyError) as exc:
        parser.exit(1, str(exc) + "\n")


if __name__ == "__main__":
    main()
